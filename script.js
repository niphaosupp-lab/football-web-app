let passed=false,lastScore=0;
function checkQuiz(){
  let score=0;
  questions.forEach((x,i)=>{
    const pick=document.querySelector(`input[name="q${i}"]:checked`);
    if(pick && Number(pick.value)===x.c) score++;
  });
  lastScore=Math.round(score/questions.length*100);
  passed=lastScore>=80;
  document.getElementById("result").innerHTML=`ได้คะแนน ${score}/${questions.length} (${lastScore}%)<br>`+
    (passed?"🎉 ผ่านเกณฑ์ สามารถสร้างเกียรติบัตรได้":"ยังไม่ผ่านเกณฑ์ 80% ลองทบทวนบทเรียนแล้วทำใหม่");
}
